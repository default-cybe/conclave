}

/// What a pairing code is for: the app (signs in as you) or a computer's command line.
public enum PairKind: String, Sendable, CaseIterable {
    case app = "client"
    case computer = "device"

    public var label: String { self == .app ? "App" : "Command line" }
}

public enum FileGroup: String, WireEnum {
    case generated, screenshot, uploaded
    public static let fallback = FileGroup.generated
}

/// One file of a session (GET /api/sessions/:id/files, newest first): shared or generated by a
/// tool (toolUseId), a tool's screenshot (part), or a picture or document someone attached.
public struct SessionFile: Sendable, Hashable, Codable, Identifiable {
    public var key: String
    public var group: FileGroup = .generated
    public var name = ""
    public var mediaType = ""
    public var size: Int64?
    public var at: Int64 = 0
    public var messageId = ""
    public var index = 0
    public var part: Int?
    public var toolUseId: String?
    public var image: Int?

    public var id: String { key }

    public init(key: String, group: FileGroup = .generated, name: String = "", mediaType: String = "", size: Int64? = nil, at: Int64 = 0,
                messageId: String = "", index: Int = 0, part: Int? = nil, toolUseId: String? = nil, image: Int? = nil) {
        self.key = key
        self.group = group
        self.name = name
        self.mediaType = mediaType
        self.size = size
        self.at = at
        self.messageId = messageId
        self.index = index
        self.part = part
        self.toolUseId = toolUseId
        self.image = image
    }

    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        key = try c.decode(String.self, forKey: .key)
        group = try c.or(.group, .generated)
        name = try c.or(.name, "")
        mediaType = try c.or(.mediaType, "")
        size = try? c.opt(.size)
        at = try c.or(.at, 0)
        messageId = try c.or(.messageId, "")
        index = try c.or(.index, 0)
        part = try c.opt(.part)
        toolUseId = try c.opt(.toolUseId)
        image = try c.opt(.image)
    }
}

