        self.defaultModel = defaultModel
        self.smallModel = smallModel
        self.defaultAgent = defaultAgent
    }
}

/// GET /api/me: who this token signs in as, owner or member, and their own defaults.
public struct Me: Sendable, Hashable, Codable {
    public var id = ""
    public var name = ""
    public var displayName: String?
    public var role = "owner"
    public var email: String?
    public var preferences = MePreferences()

    public init(id: String = "", name: String = "", role: String = "owner", preferences: MePreferences = MePreferences()) {
        self.id = id
        self.name = name
        self.role = role
        self.preferences = preferences
    }

    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        id = try c.or(.id, "")
        name = try c.or(.name, "")
        displayName = try c.opt(.displayName)
        role = try c.or(.role, "owner")
        email = try c.opt(.email)
        preferences = (try? c.opt(.preferences)) ?? MePreferences()
    }

    public var shownName: String {
        let d = displayName?.trimmingCharacters(in: .whitespaces) ?? ""
        return d.isEmpty ? (name.isEmpty ? "Owner" : name) : d
    }
}
