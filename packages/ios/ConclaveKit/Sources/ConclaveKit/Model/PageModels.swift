// Wire shapes of the pages past the chat: devices, pairing codes, the session's files and /api/me
// (core/src/types.ts Device, core/src/client/index.ts PairingInfo, core/src/session/files.ts,
// core/src/client/people.ts MeDto). Missing fields fall back, as the Kotlin client's.

public struct MachineInfo: Sendable, Hashable, Codable {
    public var hostname = ""
    public var platform = ""
    public var arch = ""

    public init(hostname: String = "", platform: String = "", arch: String = "") {
        self.hostname = hostname
        self.platform = platform
        self.arch = arch
    }

    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        hostname = try c.or(.hostname, "")
        platform = try c.or(.platform, "")
        arch = try c.or(.arch, "")
    }
}

/// A computer the hub can run work on. `local` is the hub's own row, always online.
public struct Device: Sendable, Hashable, Codable, Identifiable {
    public var id: String
    public var name = ""
    public var online = false
    public var lastSeenAt: Int64?
    public var info: MachineInfo?
    public var roots: [String] = []
    public var createdAt: Int64 = 0

    public init(id: String, name: String = "", online: Bool = false, lastSeenAt: Int64? = nil, info: MachineInfo? = nil) {
        self.id = id
        self.name = name
        self.online = online
        self.lastSeenAt = lastSeenAt
        self.info = info
    }

    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        id = try c.decode(String.self, forKey: .id)
        name = try c.or(.name, "")
        online = try c.or(.online, false)
        lastSeenAt = try c.opt(.lastSeenAt)
        info = try? c.opt(.info)
        roots = try c.or(.roots, [])
        createdAt = try c.or(.createdAt, 0)
    }
}

