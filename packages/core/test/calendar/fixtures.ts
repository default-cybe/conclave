/** A VCALENDAR around the given lines. */
export function ics(lines: string[]): string {
  return ['BEGIN:VCALENDAR', 'VERSION:2.0', 'PRODID:-//Test//EN', ...lines, 'END:VCALENDAR'].join('\r\n') + '\r\n';
}
