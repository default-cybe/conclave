//! Claude Code sessions (importers/claude-code.ts): ~/.claude/projects/<dir>/<id>.jsonl
//! and subagent transcripts under <id>/subagents. The reader walks the live
//! branch from last-prompt.leafUuid and tags every user message with its origin.

use super::{bump, content, content_mut, message, role, sanitize_tool_id, text_block, truncate_title, Converted, FoundFile};
use crate::js::{self, as_str, coalesce, encode_base64, is_obj, js_string, nullish, prop, truthy, Obj};
use regex::Regex;
use serde_json::{json, Map, Value};
use std::collections::{HashMap, HashSet};
use std::sync::OnceLock;

const KNOWN_LINES: &[&str] = &["user", "assistant", "system", "summary", "custom-title", "ai-title", "last-prompt", "file-history-snapshot", "attachment", "queue-operation", "progress", "model_refusal_fallback", "tag", "agent-name", "pr-link"];
const STOP_REASONS: &[&str] = &["end_turn", "tool_use", "max_tokens", "stop_sequence", "refusal", "pause_turn"];

/// Session files and subagent transcripts, with the parent session id for subagents.
pub fn files(home: &str) -> Vec<(FoundFile, Option<String>)> {
    let dir = crate::paths::join_slash(&[&super::home_root(home, ".claude"), "projects"]);
    static UUIDISH: OnceLock<Regex> = OnceLock::new();
    let uuidish = UUIDISH.get_or_init(|| Regex::new(r"(?i)^[0-9a-f-]{8,}$").unwrap());
    let all = super::walk_files(&dir, 5, &|n| n.ends_with(".jsonl"), &|name, depth| match depth {
        // memory/ and tool-results/ hold other files; only <id>/subagents/... nests transcripts
        1 => !uuidish.is_match(name),
        2 => name != "subagents",
        3 => name != "workflows",
        _ => false,
    });
    let mut out = Vec::new();
    for f in all {
        let rel: Vec<String> = f.path.get(dir.len() + 1..).unwrap_or("").split('/').map(str::to_string).collect();
        if rel.len() == 2 {
            out.push((f, None));
        } else if rel.len() >= 4 && rel[2] == "subagents" {
            let parent = rel[1].clone();
            out.push((f, Some(parent)));
        }
    }
    out
}

fn re(cell: &'static OnceLock<Regex>, src: &str) -> &'static Regex {
    cell.get_or_init(|| Regex::new(src).unwrap())
}

/// stripWrappers: system reminders go entirely, persisted output keeps its body.
pub fn strip_wrappers(text: &str) -> String {
    static A: OnceLock<Regex> = OnceLock::new();
    static B: OnceLock<Regex> = OnceLock::new();
    static C: OnceLock<Regex> = OnceLock::new();
    let t = re(&A, r"(?s)<system-reminder>.*?</system-reminder>").replace_all(text, "");
    let t = re(&B, r"</?persisted-output>").replace_all(&t, "");
    let t = re(&C, r"\n{3,}").replace_all(&t, "\n\n");
    js::trim(&t).to_string()
}

/// cleanUserText: None for lines that are not real prompts.
pub fn clean_user_text(text: &str) -> Option<String> {
    static LOCAL: OnceLock<Regex> = OnceLock::new();
    static CMD: OnceLock<Regex> = OnceLock::new();
    static ARGS: OnceLock<Regex> = OnceLock::new();
    static BASH: OnceLock<Regex> = OnceLock::new();
    let t = strip_wrappers(text);
    if t.is_empty() {
        return None;
    }
    if re(&LOCAL, r"^<(local-command-stdout|local-command-stderr|bash-stdout|bash-stderr)>").is_match(&t) {
        return None;
    }
    if t.starts_with("Caveat: The messages below were generated by the user while running local commands") {
        return None;
    }
    if let Some(c) = re(&CMD, r"<command-name>([^<]*)</command-name>").captures(&t) {
        let args = re(&ARGS, r"(?s)<command-args>(.*?)</command-args>").captures(&t).map(|a| js::trim(a.get(1).unwrap().as_str()).to_string());
        let name = js::trim(c.get(1).unwrap().as_str());
        let name = if name.starts_with('/') { name.to_string() } else { format!("/{name}") };
        return Some(match args.filter(|a| !a.is_empty()) {
            Some(a) => format!("{name} {a}"),
            None => name,
        });
    }
    if let Some(b) = re(&BASH, r"(?s)^<bash-input>(.*?)</bash-input>$").captures(&t) {
        return Some(format!("!{}", b.get(1).unwrap().as_str()));
    }
    Some(t)
}

fn starts_with_tag(t: &str, tag: &str) -> bool {
    t.strip_prefix(tag).is_some_and(|rest| !rest.chars().next().is_some_and(|c| c.is_ascii_alphanumeric() || c == '_'))
}

/// lineOrigin: who wrote a user line.
fn line_origin(l: &Obj, text: &str) -> &'static str {
    if as_str(l.get("promptSource")) == Some("system") {
        return "system";
    }
    let raw = coalesce(&[prop(l.get("origin"), "kind"), l.get("origin"), prop(l.get("turnOrigin"), "kind"), l.get("turnOrigin")]);
    let k = as_str(raw).map(js::lower).unwrap_or_default();
    if !k.is_empty() {
        if k.contains("task") {
            return "task";
        }
        if k.contains("peer") || k.contains("teammate") || k == "agent" {
            return "peer";
        }
        if k.contains("sdk") {
            return "sdk";
        }
        if k.contains("system") || k.contains("hook") {
            return "system";
        }
    }
    let t = js::trim_start(text);
    if t.starts_with("<task-notification>") {
        return "task";
    }
    if starts_with_tag(t, "<peer-message") || starts_with_tag(t, "<agent-message") || starts_with_tag(t, "<teammate-message") {
        return "peer";
    }
    "human"
}

struct Line {
    v: Obj,
    i: usize,
}

impl Line {
    fn s(&self, k: &str) -> Option<&str> {
        as_str(self.v.get(k))
    }
    fn uuid(&self) -> Option<&str> {
        self.s("uuid")
    }
}

/// activeLines: the live conversation, walked back from the leaf.
fn active_lines(lines: &[Line], keep_sidechain: bool) -> Vec<usize> {
    let mut by_uuid: HashMap<&str, usize> = HashMap::new();
    let mut children: HashMap<&str, Vec<usize>> = HashMap::new();
    let mut leaf_id: Option<&str> = None;
    let mut retracted: HashSet<&str> = HashSet::new();
    for (idx, l) in lines.iter().enumerate() {
        if let Some(u) = l.uuid() {
            by_uuid.insert(u, idx);
        }
        if let Some(p) = l.s("parentUuid") {
            children.entry(p).or_default().push(idx);
        }
        if l.s("type") == Some("last-prompt") {
            if let Some(leaf) = l.s("leafUuid") {
                leaf_id = Some(leaf);
            }
        }
        if l.s("type") == Some("model_refusal_fallback") || l.s("subtype") == Some("model_refusal_fallback") {
            if let Some(Value::Array(ids)) = l.v.get("retractedMessageUuids") {
                for id in ids {
                    if let Some(s) = id.as_str() {
                        retracted.insert(s);
                    }
                }
            }
        }
    }
    let is_retracted = |l: &Line| l.uuid().is_some_and(|u| retracted.contains(u));
    let msg_lines: Vec<usize> = lines
        .iter()
        .enumerate()
        .filter(|(_, l)| matches!(l.s("type"), Some("user" | "assistant" | "attachment" | "system")) && (keep_sidechain || !truthy(l.v.get("isSidechain"))) && !is_retracted(l))
        .map(|(i, _)| i)
        .collect();
    let Some(leaf_idx) = leaf_id.and_then(|id| by_uuid.get(id).copied()) else { return msg_lines };

    // the last prompt's replies come after it: follow the newest child down to the end
    let mut leaf = leaf_idx;
    for _ in 0..100_000 {
        let Some(u) = lines[leaf].uuid() else { break };
        let kids: Vec<usize> = children.get(u).map(|k| k.iter().copied().filter(|c| !is_retracted(&lines[*c]) && (keep_sidechain || !truthy(lines[*c].v.get("isSidechain")))).collect()).unwrap_or_default();
        match kids.last() {
            Some(k) => leaf = *k,
            None => break,
        }
    }
    // a line without a uuid can be the leaf; it joins the chain as "no id", as in the TypeScript reader
    let mut chain: HashSet<Option<&str>> = HashSet::new();
    let mut chain_order: Vec<usize> = Vec::new();
    let mut cur = Some(leaf);
    // a compact boundary passed whose earlier history the walk has not reached yet
    let mut open: Option<usize> = None;
    for _ in 0..1_000_000 {
        if cur.is_none_or(|c| chain.contains(&lines[c].uuid())) {
            // the boundary's back link is missing, dead or loops (newer builds re-write a preserved tail after it): go on from the newest line written before it
            let before = open.take().unwrap_or(0);
            cur = (0..before).rev().find(|&i| {
                let x = &lines[i];
                matches!(x.s("type"), Some("user" | "assistant")) && !truthy(x.v.get("isSidechain")) && x.uuid().is_some_and(|u| !chain.contains(&Some(u)) && !retracted.contains(u))
            });
        }
        let Some(c) = cur else { break };
        let u = lines[c].uuid();
        chain.insert(u);
        chain_order.push(c);
        if open.is_some_and(|b| c < b) {
            open = None;
        }
        if lines[c].s("subtype") == Some("compact_boundary") {
            open = Some(c);
        }
        let next = lines[c].s("parentUuid").or_else(|| lines[c].s("logicalParentUuid"));
        cur = next.and_then(|n| by_uuid.get(n).copied());
    }
    let mut tool_ids: HashSet<String> = HashSet::new();
    let mut msg_ids: HashSet<&str> = HashSet::new();
    for &c in &chain_order {
        let l = &lines[c];
        if l.uuid().is_none() {
            continue;
        }
        if l.s("type") == Some("assistant") && truthy(l.v.get("message")) {
            if let Some(id) = as_str(prop(l.v.get("message"), "id")) {
                msg_ids.insert(id);
            }
            if let Some(Value::Array(blocks)) = prop(l.v.get("message"), "content") {
                for b in blocks {
                    if as_str(prop(Some(b), "type")) == Some("tool_use") && truthy(prop(Some(b), "id")) {
                        tool_ids.insert(js_string(prop(Some(b), "id")));
                    }
                }
            }
        }
    }
    // a uuid written twice (a preserved message re-written after a boundary) shows once, at its first place
    let mut seen: HashSet<&str> = HashSet::new();
    msg_lines
        .into_iter()
        .filter(|&i| {
            let l = &lines[i];
            if l.uuid().is_some_and(|u| !seen.insert(u)) {
                return false;
            }
            if chain.contains(&l.uuid()) {
                return true;
            }
            if l.s("type") == Some("assistant") && as_str(prop(l.v.get("message"), "id")).is_some_and(|id| msg_ids.contains(id)) {
                return true;
            }
            if l.s("type") == Some("user") {
                if let Some(Value::Array(blocks)) = prop(l.v.get("message"), "content") {
                    let results: Vec<&Value> = blocks.iter().filter(|b| as_str(prop(Some(b), "type")) == Some("tool_result")).collect();
                    return !results.is_empty() && results.iter().all(|b| tool_ids.contains(&js_string(prop(Some(b), "tool_use_id"))));
                }
            }
            false
        })
        .collect()
}

/// Convert a Claude Code JSONL transcript. Unknown lines are counted, never dropped in silence.
pub fn convert(bytes: &[u8], subagent: bool, parent: Option<String>) -> Converted {
    let mut unknown = Map::new();
    let lines: Vec<Line> = super::parse_jsonl(bytes).into_iter().enumerate().map(|(i, v)| Line { v, i }).collect();
    let mut native_id: Option<String> = None;
    let mut cwd: Option<String> = None;
    let mut git_branch: Option<String> = None;
    let mut entrypoint: Option<String> = None;
    let mut custom_title: Option<String> = None;
    let mut ai_title: Option<String> = None;
    let mut model: Option<String> = None;
    let mut summaries: Vec<(Option<Value>, String)> = Vec::new();
    let mut uuids: HashSet<String> = HashSet::new();
    let mut sidechain = 0usize;
    for l in &lines {
        if let Some(u) = l.uuid() {
            uuids.insert(u.to_string());
        }
        match l.v.get("type") {
            Some(Value::String(t)) if KNOWN_LINES.contains(&t.as_str()) => {}
            other => {
                let name = if nullish(other) { "none".to_string() } else { js_string(other) };
                bump(&mut unknown, &format!("line:{name}"));
            }
        }
        if native_id.as_deref().is_none_or(str::is_empty) {
            if let Some(s) = l.s("sessionId") {
                native_id = Some(s.to_string());
            }
        }
        if cwd.is_none() {
            if let Some(s) = l.s("cwd") {
                cwd = Some(s.to_string());
            }
        }
        if let Some(s) = l.s("gitBranch").filter(|s| !s.is_empty()) {
            git_branch = Some(s.to_string());
        }
        if entrypoint.is_none() {
            if let Some(s) = l.s("entrypoint") {
                entrypoint = Some(s.to_string());
            }
        }
        if truthy(l.v.get("isSidechain")) {
            sidechain += 1;
        }
        let ty = l.s("type");
        if ty == Some("summary") && l.s("summary").is_some() {
            summaries.push((l.v.get("leafUuid").cloned(), l.s("summary").unwrap().to_string()));
        } else if ty == Some("custom-title") {
            if let Some(t) = as_str(coalesce(&[l.v.get("customTitle"), l.v.get("title")])) {
                custom_title = Some(t.to_string());
            }
        } else if ty == Some("ai-title") {
            if let Some(t) = as_str(coalesce(&[l.v.get("aiTitle"), l.v.get("title")])) {
                ai_title = Some(t.to_string());
            }
        }
    }

    let mut out: Vec<Obj> = Vec::new();
    let mut msg_ids: Vec<Option<String>> = Vec::new();
    let mut last_ts = 0.0f64;
    let meta = |l: &Line, extra: Vec<(&str, Value)>| -> Value {
        let id = l.uuid().map(str::to_string).unwrap_or_else(|| format!("line{}", l.i));
        let mut m = Map::new();
        m.insert("external".into(), json!({ "source": "claude-code", "id": id }));
        for (k, v) in extra {
            m.insert(k.into(), v);
        }
        Value::Object(m)
    };

    // a file made only of sidechain lines is a subagent transcript (older builds kept them in the main file)
    let talk = lines.iter().filter(|l| matches!(l.s("type"), Some("user" | "assistant"))).count();
    let is_sub = subagent || (sidechain > 0 && sidechain >= talk);
    for idx in active_lines(&lines, is_sub) {
        let l = &lines[idx];
        let ts = js::parse_time(l.v.get("timestamp"), last_ts);
        if ts != 0.0 && !ts.is_nan() {
            last_ts = ts;
        }
        let ty = l.s("type");

        if ty == Some("assistant") && is_obj(l.v.get("message")) {
            let msg = l.v.get("message").unwrap();
            let mdl = prop(Some(msg), "model");
            if as_str(mdl) == Some("<synthetic>") && !has_real_content(prop(Some(msg), "content")) {
                continue;
            }
            let blocks = assistant_blocks(prop(Some(msg), "content"), &mut unknown);
            let msg_id = as_str(prop(Some(msg), "id")).map(str::to_string);
            let merge_id = msg_id.as_deref().filter(|s| !s.is_empty());
            let stop = as_str(prop(Some(msg), "stop_reason")).filter(|s| STOP_REASONS.contains(s)).map(str::to_string);
            let usage = to_usage(prop(Some(msg), "usage"));
            if let (Some(cur), Some(Some(cur_id))) = (out.last_mut(), msg_ids.last()) {
                if role(cur) == "assistant" && merge_id.is_some() && merge_id == Some(cur_id.as_str()) {
                    content_mut(cur).extend(blocks);
                    if let Some(u) = usage {
                        cur.insert("usage".into(), u);
                    }
                    if let Some(s) = stop {
                        cur.insert("stopReason".into(), json!(s));
                    }
                    continue;
                }
            }
            if blocks.is_empty() {
                continue;
            }
            let mut m = message("assistant", "normal", blocks, ts, meta(l, vec![]));
            if let Some(name) = as_str(mdl).filter(|n| *n != "<synthetic>") {
                let full = format!("anthropic/{name}");
                m.insert("model".into(), json!(full));
                model = Some(full);
            }
            if let Some(u) = usage {
                m.insert("usage".into(), u);
            }
            if let Some(s) = stop {
                m.insert("stopReason".into(), json!(s));
            }
            out.push(m);
            msg_ids.push(msg_id);
            continue;
        }

        // a prompt typed while a turn ran, delivered in place
        if ty == Some("attachment") {
            let a = l.v.get("attachment");
            if as_str(prop(a, "type")) == Some("queued_command") && prop(a, "humanTurn") != Some(&Value::Bool(false)) {
                if let Some(t) = as_str(prop(a, "prompt")).and_then(clean_user_text) {
                    out.push(message("user", "normal", vec![text_block(&t)], ts, meta(l, vec![("origin", json!("human")), ("queued", json!(true))])));
                    msg_ids.push(None);
                }
            } else if let Some(t) = as_str(prop(a, "type")) {
                bump(&mut unknown, &format!("attachment:{t}"));
            }
            continue;
        }

        if ty == Some("user") && truthy(l.v.get("message")) && !truthy(l.v.get("isMeta")) {
            let blocks = user_blocks(prop(l.v.get("message"), "content"), &mut unknown);
            if blocks.is_empty() {
                continue;
            }
            let only_results = blocks.iter().all(|b| super::block_type(b) == "tool_result");
            if only_results {
                // parallel tool results arrive as separate lines; the API wants them in one user turn
                if let Some(cur) = out.last_mut() {
                    if role(cur) == "user" && content(cur).iter().all(|b| super::block_type(b) == "tool_result") {
                        content_mut(cur).extend(blocks);
                        continue;
                    }
                }
                out.push(message("user", "normal", blocks, ts, meta(l, vec![("origin", json!("system"))])));
                msg_ids.push(None);
                continue;
            }
            let text = blocks.iter().filter(|b| super::block_type(b) == "text").map(|b| js_string(prop(Some(b), "text"))).collect::<Vec<_>>().join("\n");
            if truthy(l.v.get("isCompactSummary")) {
                out.push(message("user", "summary", vec![text_block(&text)], ts, meta(l, vec![("origin", json!("system"))])));
                msg_ids.push(None);
                continue;
            }
            let origin = line_origin(&l.v, &text);
            let author = match origin {
                "task" => Some("Background task"),
                "peer" => Some("Peer agent"),
                _ => None,
            };
            let m = match author {
                Some(a) => {
                    let mut m = Map::new();
                    m.insert("role".into(), json!("user"));
                    m.insert("kind".into(), json!("aside"));
                    m.insert("author".into(), json!(a));
                    m.insert("content".into(), Value::Array(blocks));
                    m.insert("createdAt".into(), js::num(ts));
                    m.insert("meta".into(), meta(l, vec![("origin", json!(origin))]));
                    m
                }
                None => message("user", "normal", blocks, ts, meta(l, vec![("origin", json!(origin))])),
            };
            out.push(m);
            msg_ids.push(None);
        }
    }

    let own: Vec<&(Option<Value>, String)> = summaries.iter().filter(|(leaf, _)| truthy(leaf.as_ref()) && leaf.as_ref().and_then(Value::as_str).is_some_and(|s| uuids.contains(s))).collect();
    let first_human = out.iter().find(|m| role(m) == "user" && super::kind(m) == "normal" && super::meta_origin(m) == Some("human"));
    let first_text = first_human.and_then(|m| content(m).iter().find(|b| super::block_type(b) == "text")).map(|b| js_string(prop(Some(b), "text")));
    let title = custom_title.or(ai_title).or_else(|| own.last().map(|s| s.1.clone())).or(first_text).or_else(|| summaries.last().map(|s| s.1.clone()));
    let automation = entrypoint.as_deref().is_some_and(|e| e.starts_with("sdk-"));
    Converted {
        source: "claude-code",
        native_id,
        // a main file is <sessionId>.jsonl, so its id goes in the fingerprint (importers/claude-code.ts); a subagent carries its parent's
        native_id_unique: !is_sub,
        title: title.filter(|t| !t.is_empty()).map(|t| truncate_title(&t)),
        cwd,
        git_branch,
        repo: None,
        model,
        kind: if is_sub {
            "subagent"
        } else if automation {
            "automation"
        } else {
            "main"
        },
        parent_native_id: parent,
        entrypoint,
        messages: out,
        unknown,
        learnable: true,
    }
}

fn has_real_content(content: Option<&Value>) -> bool {
    static NO_RESPONSE: OnceLock<Regex> = OnceLock::new();
    let re = NO_RESPONSE.get_or_init(|| Regex::new(r"^No response requested").unwrap());
    match content {
        Some(Value::Array(a)) => a.iter().any(|b| {
            let t = as_str(prop(Some(b), "type"));
            t == Some("tool_use") || (t == Some("text") && truthy(prop(Some(b), "text")) && !re.is_match(&js_string(prop(Some(b), "text"))))
        }),
        _ => false,
    }
}

fn number_or_zero(v: Option<&Value>) -> Value {
    match v {
        Some(Value::Number(n)) if n.as_f64().is_some_and(f64::is_finite) => Value::Number(n.clone()),
        _ => json!(0),
    }
}

fn to_usage(u: Option<&Value>) -> Option<Value> {
    if !js::is_object_like(u) {
        return None;
    }
    Some(json!({
        "inputTokens": number_or_zero(prop(u, "input_tokens")),
        "outputTokens": number_or_zero(prop(u, "output_tokens")),
        "cacheReadTokens": number_or_zero(prop(u, "cache_read_input_tokens")),
        "cacheWriteTokens": number_or_zero(prop(u, "cache_creation_input_tokens")),
    }))
}

fn tool_use(id: &str, name: String, input: Value) -> Value {
    json!({ "type": "tool_use", "id": sanitize_tool_id(id), "name": name, "input": input })
}

/// `isObj(b.input) ? b.input : { input: b.input }` (undefined drops out).
fn input_of(v: Option<&Value>) -> Value {
    match v {
        Some(Value::Object(_)) => v.unwrap().clone(),
        None => json!({}),
        Some(other) => json!({ "input": other }),
    }
}

fn assistant_blocks(content: Option<&Value>, unknown: &mut Obj) -> Vec<Value> {
    match content {
        Some(Value::String(s)) => {
            if s.is_empty() {
                vec![]
            } else {
                vec![text_block(s)]
            }
        }
        Some(Value::Array(a)) => {
            let mut out = Vec::new();
            for b in a {
                if !js::is_object_like(Some(b)) {
                    continue;
                }
                let ty = prop(Some(b), "type");
                match as_str(ty) {
                    Some("text") => {
                        if let Some(t) = as_str(prop(Some(b), "text")).filter(|t| !t.is_empty()) {
                            out.push(text_block(t));
                        }
                    }
                    Some("thinking") => {
                        if let Some(t) = as_str(prop(Some(b), "thinking")) {
                            let mut o = Map::new();
                            o.insert("type".into(), json!("thinking"));
                            o.insert("thinking".into(), json!(t));
                            if truthy(prop(Some(b), "signature")) {
                                o.insert("signature".into(), prop(Some(b), "signature").unwrap().clone());
                            }
                            out.push(Value::Object(o));
                        }
                    }
                    Some("redacted_thinking") => {
                        if let Some(d) = as_str(prop(Some(b), "data")) {
                            out.push(json!({ "type": "redacted_thinking", "data": d }));
                        }
                    }
                    Some("tool_use") | Some("server_tool_use") => {
                        let id = coalesce(&[prop(Some(b), "id")]).map(|v| js_string(Some(v))).unwrap_or_default();
                        let name = coalesce(&[prop(Some(b), "name")]).map(|v| js_string(Some(v))).unwrap_or_else(|| "tool".into());
                        out.push(tool_use(&id, name, input_of(prop(Some(b), "input"))));
                    }
                    Some("web_search_tool_result") => {}
                    _ => bump(unknown, &format!("content:{}", js_string(ty))),
                }
            }
            out
        }
        _ => vec![],
    }
}

fn user_blocks(content: Option<&Value>, unknown: &mut Obj) -> Vec<Value> {
    match content {
        Some(Value::String(s)) => clean_user_text(s).map(|t| vec![text_block(&t)]).unwrap_or_default(),
        Some(Value::Array(a)) => {
            let mut out = Vec::new();
            for b in a {
                if !js::is_object_like(Some(b)) {
                    continue;
                }
                let ty = prop(Some(b), "type");
                match as_str(ty) {
                    Some("text") => {
                        if let Some(t) = as_str(prop(Some(b), "text")).and_then(clean_user_text) {
                            out.push(text_block(&t));
                        }
                    }
                    Some("image") => {
                        if let Some(img) = media_block(b) {
                            out.push(img);
                        }
                    }
                    Some("document") => {
                        if let Some(Value::Object(mut doc)) = media_block(b) {
                            doc.insert("type".into(), json!("document"));
                            if truthy(prop(Some(b), "title")) {
                                doc.insert("title".into(), prop(Some(b), "title").unwrap().clone());
                            }
                            out.push(Value::Object(doc));
                        }
                    }
                    Some("tool_result") => {
                        let id = coalesce(&[prop(Some(b), "tool_use_id")]).map(|v| js_string(Some(v))).unwrap_or_default();
                        let mut o = Map::new();
                        o.insert("type".into(), json!("tool_result"));
                        o.insert("toolUseId".into(), json!(sanitize_tool_id(&id)));
                        o.insert("content".into(), tool_result_content(prop(Some(b), "content")));
                        if truthy(prop(Some(b), "is_error")) {
                            o.insert("isError".into(), json!(true));
                        }
                        o.insert("meta".into(), json!({ "external": true }));
                        out.push(Value::Object(o));
                    }
                    _ => bump(unknown, &format!("content:{}", js_string(ty))),
                }
            }
            out
        }
        _ => vec![],
    }
}

fn media_block(b: &Value) -> Option<Value> {
    let src = prop(Some(b), "source");
    if !truthy(src) {
        return None;
    }
    let ty = prop(Some(b), "type").cloned().unwrap_or(Value::Null);
    let media = || coalesce(&[prop(src, "media_type")]).cloned().unwrap_or_else(|| json!("application/octet-stream"));
    match as_str(prop(src, "type")) {
        Some("base64") if as_str(prop(src, "data")).is_some() => Some(json!({ "type": ty, "mediaType": media(), "data": prop(src, "data").unwrap() })),
        Some("url") if as_str(prop(src, "url")).is_some() => Some(json!({ "type": ty, "mediaType": media(), "url": prop(src, "url").unwrap() })),
        Some("text") if as_str(prop(src, "data")).is_some() => Some(json!({ "type": "document", "mediaType": "text/plain", "data": encode_base64(as_str(prop(src, "data")).unwrap().as_bytes()) })),
        _ => None,
    }
}

fn tool_result_content(c: Option<&Value>) -> Value {
    match c {
        Some(Value::String(s)) => Value::String(strip_wrappers(s)),
        Some(Value::Array(a)) => {
            let mut out: Vec<Value> = Vec::new();
            for b in a {
                match as_str(prop(Some(b), "type")) {
                    Some("text") if as_str(prop(Some(b), "text")).is_some() => out.push(text_block(&strip_wrappers(as_str(prop(Some(b), "text")).unwrap()))),
                    Some("image") => {
                        if let Some(img) = media_block(b) {
                            out.push(img);
                        }
                    }
                    _ => {}
                }
            }
            if out.iter().all(|b| super::block_type(b) == "text") {
                Value::String(out.iter().map(|b| js_string(prop(Some(b), "text"))).collect::<Vec<_>>().join("\n"))
            } else {
                Value::Array(out)
            }
        }
        None | Some(Value::Null) => Value::String(String::new()),
        Some(other) => Value::String(js::stringify(other)),
    }
}

